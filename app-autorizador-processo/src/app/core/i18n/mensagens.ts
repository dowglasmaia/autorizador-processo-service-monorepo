export type Mensagens = typeof MENSAGENS;

/** Mensagem do catálogo para um `code` do contrato; desconhecido ou ausente cai na genérica. */
export function mensagemDoErro(code: string | undefined): string {
  if (code !== undefined && Object.hasOwn(MENSAGENS.erros.porCode, code)) {
    return MENSAGENS.erros.porCode[code as ProblemCode];
  }
  return MENSAGENS.erros.generico;
}
